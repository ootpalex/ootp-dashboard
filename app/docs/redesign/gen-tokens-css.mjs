#!/usr/bin/env node
// Prints tokens.css from src/theme.js (TOKENS + encodings) so the CSS layer can
// never drift from the JS source of truth.   Usage: node gen-tokens-css.mjs > tokens.css
import { TOKENS, GRADE, FV_TIER_COLORS, POS, LEVEL, PRONE, ZHEAT } from "../../src/theme.js";

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([a-zA-Z])(\d)/g, "$1-$2").toLowerCase();
const safe = (s) => String(s).replace(/\+/g, "plus").toLowerCase();
const out = [];
const emit = (name, value, note) => out.push(`  --${name}: ${value};${note ? `  /* ${note} */` : ""}`);

const walk = (obj, prefix = "") => Object.entries(obj).forEach(([k, v]) => {
  if (k === "fonts" || k === "radius" || k === "radiusPill" || k === "fontSize") return;
  if (v && typeof v === "object") walk(v, prefix + kebab(k) + "-");
  else emit(prefix + kebab(k), v);
});
walk(TOKENS);
emit("font-ui", TOKENS.fonts.ui); emit("font-narrow", TOKENS.fonts.narrow);
emit("radius", `${TOKENS.radius}px`); emit("radius-pill", `${TOKENS.radiusPill}px`, "FV tier pills only"); emit("font-size", `${TOKENS.fontSize}px`);
out.push("", "  /* 20–80 grade ramp (text) */");
Object.entries(GRADE).forEach(([g, hex]) => emit(`g${g}`, hex));
out.push("", "  /* FV tier pills: fill + ink */");
Object.entries(FV_TIER_COLORS).forEach(([t, c]) => { emit(`tier-${safe(t)}-bg`, c.bg); emit(`tier-${safe(t)}-text`, c.text); });
out.push("", "  /* positions: text + chip fill (= mix(oklab, text 10%, panel)) */");
Object.entries(POS).forEach(([p, c]) => { emit(`pos-${safe(p)}`, c.text); emit(`pos-${safe(p)}-chip`, c.chip); });
out.push("", "  /* level ladder: fill / ink / ring; -plain = levelColor() text fallback */");
Object.entries(LEVEL).forEach(([l, c]) => { emit(`lvl-${safe(l)}-bg`, c.bg); emit(`lvl-${safe(l)}-text`, c.text); emit(`lvl-${safe(l)}-ring`, c.ring); emit(`lvl-${safe(l)}-plain`, c.plain); });
out.push("", "  /* injury proneness */");
Object.entries(PRONE).forEach(([p, c]) => { emit(`prone-${safe(p).replace(/\s+/g, "-")}`, c.color); emit(`prone-${safe(p).replace(/\s+/g, "-")}-weight`, c.weight); });
out.push("", "  /* z-heat endpoints: fill = color-mix(in oklab, var(--zneg|--zpos) calc(|z|/2.5*100%), var(--panel)); text flips to --bg at ≥80% */");
emit("zneg", ZHEAT.neg); emit("zpos", ZHEAT.pos); emit("zmid", ZHEAT.mid);

console.log(`/* tokens.css — GENERATED by gen-tokens-css.mjs from src/theme.js; do not edit by hand.
   "Night Scorecard", graphite ground. Same names as TOKENS, kebab-cased.
   index.html needs this line in <head> (Archivo + Archivo Narrow; no monospace):
   <link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
   <link href="https://fonts.googleapis.com/css2?family=Archivo:wght@400;500;600;700;800&family=Archivo+Narrow:wght@400;500;600;700&display=swap" rel="stylesheet">
*/
:root {
${out.join("\n")}
  color-scheme: dark;
}

/* globals (replaces index.html's inline body rule and the 145° gradient) */
* { box-sizing: border-box; }
html, body { margin: 0; padding: 0; }
body {
  background: var(--bg);
  color: var(--text);
  font-family: var(--font-ui);
  font-size: var(--font-size);
  line-height: 1.4;
  -webkit-font-smoothing: antialiased;
  font-variant-numeric: tabular-nums;
}
button, input, select { font: inherit; color: inherit; }
:focus-visible { outline: 2px solid var(--focus); outline-offset: 1px; }`);
